        0x0698=>[0xFB8A,0xFB8B,0,0],0x06A9=>[0xFB8E,0xFB8F,0xFB90,0xFB91],0x06AF=>[0xFB92,0xFB93,0xFB94,0xFB95],
        0x06CC=>[0xFBFC,0xFBFD,0xFBFE,0xFBFF],
    ];

    /**
     * @param list<int> $points
     * @return list<int>
     */
    public static function shape(array $points): array
    {
        $out=$points;
        foreach ($points as $i=>$cp) {
            if (!isset(self::FORMS[$cp])) continue;
            $prev=self::neighbor($points,$i,-1); $next=self::neighbor($points,$i,1);
            $jp=$prev!==null&&self::canNext($prev)&&self::canPrev($cp);
            $jn=$next!==null&&self::canNext($cp)&&self::canPrev($next);
            $forms=self::FORMS[$cp]; $index=$jp&&$jn?3:($jp?1:($jn?2:0));
            $out[$i]=$forms[$index]?:$forms[0];
        }
        return $out;
    }
    /** @param list<int> $points */
    private static function neighbor(array $points,int $i,int $step): ?int
    {
        for($j=$i+$step;$j>=0&&$j<count($points);$j+=$step) {
            $t=self::joining($points[$j]); if($t==='T') continue; return $t==='U'?null:$points[$j];
        }
        return null;
    }
    private static function joining(int $cp): string
    {
        $r=UnicodeData::JOINING_RANGES; $lo=0; $hi=count($r)-1;
        while($lo<=$hi){$m=intdiv($lo+$hi,2);[$a,$b,$v]=$r[$m];if($cp<$a)$hi=$m-1;elseif($cp>$b)$lo=$m+1;else return $v;}
        return 'U';
    }
    private static function canPrev(int $cp): bool { return in_array(self::joining($cp),['D','R','C'],true); }
    private static function canNext(int $cp): bool { return in_array(self::joining($cp),['D','L','C'],true); }
}
